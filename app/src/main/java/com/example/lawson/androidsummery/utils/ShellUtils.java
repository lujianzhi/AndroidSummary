    public static final String COMMAND_SH       = "sh";
    public static final String COMMAND_EXIT     = "exit\n";
    public static final String COMMAND_LINE_END = "\n";

    private static String CMD_PS = "ps ";
    private static String CMD_PS_T = "ps -t ";
